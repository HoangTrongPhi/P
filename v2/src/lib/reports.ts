/** Report export: any analysis result as a standalone HTML page or a CSV file (Excel-friendly). */
import { uiLog } from "../stores/appStore";
import { pickSavePath } from "./dialogs";
import { saveTextFile } from "./ipc";

export type Cell = string | number | boolean | null | undefined;

export interface ReportSection {
  heading?: string;
  columns: string[];
  rows: Cell[][];
}

export interface ReportDoc {
  title: string;
  /** Folder or files the report is about. */
  subject?: string;
  /** Key figures shown above the tables. */
  summary?: [string, Cell][];
  sections: ReportSection[];
}

const cellText = (c: Cell) => (c === null || c === undefined ? "" : typeof c === "boolean" ? (c ? "yes" : "no") : String(c));

function csvCell(c: Cell): string {
  const s = cellText(c);
  return /[",\r\n]/.test(s) ? `"${s.replace(/"/g, '""')}"` : s;
}

export function toCsv(doc: ReportDoc): string {
  const lines: string[] = [csvCell(doc.title)];
  if (doc.subject) lines.push(csvCell(doc.subject));
  for (const [k, v] of doc.summary ?? []) lines.push([k, v].map(csvCell).join(","));
  for (const s of doc.sections) {
    lines.push("");
    if (s.heading) lines.push(csvCell(s.heading));
    lines.push(s.columns.map(csvCell).join(","));
    for (const r of s.rows) lines.push(r.map(csvCell).join(","));
  }
  // BOM: Excel otherwise reads UTF-8 paths as ANSI.
  return "﻿" + lines.join("\r\n") + "\r\n";
}

const esc = (c: Cell) => cellText(c).replace(/[&<>"]/g, (ch) => ({ "&": "&amp;", "<": "&lt;", ">": "&gt;", '"': "&quot;" })[ch]!);

export function toHtml(doc: ReportDoc, generated = new Date()): string {
  const summary = (doc.summary ?? []).map(([k, v]) => `<div class="kpi"><span>${esc(k)}</span><b>${esc(v)}</b></div>`).join("");
  const sections = doc.sections
    .map((s) => {
      const head = s.columns.map((c) => `<th>${esc(c)}</th>`).join("");
      const body = s.rows.length ? s.rows.map((r) => `<tr>${r.map((c) => `<td>${esc(c)}</td>`).join("")}</tr>`).join("\n") : `<tr><td colspan="${s.columns.length}" class="none">Nothing to report</td></tr>`;
      return `<section>${s.heading ? `<h2>${esc(s.heading)}</h2>` : ""}<table><thead><tr>${head}</tr></thead><tbody>\n${body}\n</tbody></table></section>`;
    })
    .join("\n");
  return `<!doctype html>
<html lang="en"><head><meta charset="utf-8"><meta name="viewport" content="width=device-width,initial-scale=1">
<title>${esc(doc.title)}</title>
<style>
:root{--bg:#fff;--fg:#1d2026;--muted:#6b7280;--line:#e5e7eb;--head:#f6f7f9;--accent:#3b82f6}
@media (prefers-color-scheme:dark){:root{--bg:#0f1115;--fg:#e6e8ec;--muted:#9097a3;--line:#262a33;--head:#171a21}}
body{margin:0;padding:24px 16px;background:var(--bg);color:var(--fg);font:14px/1.45 system-ui,-apple-system,"Segoe UI",sans-serif}
main{max-width:1200px;margin:0 auto}h1{font-size:20px;margin:0 0 4px}h2{font-size:15px;margin:28px 0 8px}
.meta{color:var(--muted);font-size:12.5px;word-break:break-all}.kpis{display:flex;flex-wrap:wrap;gap:10px;margin:16px 0}
.kpi{border:1px solid var(--line);border-radius:8px;padding:8px 12px;min-width:120px}.kpi span{display:block;color:var(--muted);font-size:12px}.kpi b{font-size:16px}
section{overflow-x:auto}table{border-collapse:collapse;width:100%;font-size:12.5px}th,td{border-bottom:1px solid var(--line);padding:6px 8px;text-align:left;vertical-align:top}
th{background:var(--head);position:sticky;top:0}td{font-family:ui-monospace,Consolas,monospace;word-break:break-all}.none{color:var(--muted);font-family:inherit}
</style></head><body><main>
<h1>${esc(doc.title)}</h1>
<div class="meta">${doc.subject ? `${esc(doc.subject)}<br>` : ""}Generated by Project P on ${esc(generated.toLocaleString())}</div>
${summary ? `<div class="kpis">${summary}</div>` : ""}
${sections}
</main></body></html>
`;
}

/** File-name friendly slug of a report title. */
export function reportFileName(title: string, ext: "html" | "csv"): string {
  const slug = title.toLowerCase().replace(/[^a-z0-9]+/g, "-").replace(/^-|-$/g, "") || "report";
  return `${slug}-${new Date().toISOString().slice(0, 10)}.${ext}`;
}

/** Ask where to save (HTML or CSV by the chosen extension) and write the report. */
export async function exportReport(doc: ReportDoc, prefer: "html" | "csv" = "html"): Promise<void> {
  const filters = [
    { name: "HTML report", extensions: ["html"] },
    { name: "CSV table", extensions: ["csv"] },
  ];
  if (prefer === "csv") filters.reverse();
  const path = await pickSavePath(reportFileName(doc.title, prefer), filters);
  if (!path) return;
  const csv = /\.csv$/i.test(path);
  const target = csv || /\.html?$/i.test(path) ? path : `${path}.${prefer}`;
  try {
    await saveTextFile(target, csv ? toCsv(doc) : toHtml(doc));
    uiLog("info", `Report saved: ${target}`);
  } catch (err) {
    uiLog("error", `Report export failed: ${err}`);
  }
}

/** Path relative to `root` for display, with forward slashes. */
export function relPath(path: string, root: string | null | undefined): string {
  if (root && path.toLowerCase().startsWith(root.toLowerCase())) return path.slice(root.length).replace(/^[\\/]/, "").replace(/\\/g, "/");
  return path;
}
